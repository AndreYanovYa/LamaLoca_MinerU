    # Символы, которые мелкие LLM/OCR выдают вместо канонических KaTeX-маркеров
    # (пример из ТЗ: «x ➔ x0»). Маппинг сырого UnicodeMath -> читаемый вид.
    _MATH_CHAR_FIXES = {
        "\u2794": "\u2192",  # ➔ heavy right arrow -> →
        "\u27a1": "\u2192",  # ➡
        "\u2b95": "\u2192",  # ⮕
        "\u2192 ": "\u2192",
        "\u2798": "\u21d2",  # ➘ noise -> ⇒
        "\uff5c": "|",       # ｜ fullwidth vertical -> факториал/норма
        "\u2034": "'",       # ‴ triple prime
        "\u2033": '"',       # ″ double prime
    }

    @classmethod
    def math_guard(cls, text: str) -> str:
        """Единый математический страж промпта (Ingestion->Чанкинг->LLM->UI).

        1. clean_text — канон ограничителей KaTeX + коррекция OCR-шума;
        2. замена «диких» Unicode-стрелок/символов (➔ и т.п.) на читаемые;
        3. balance_math_delimiters — финальная чётность маркеров $/$$
           (открытый $$ в чанке роняет KaTeX с throwOnError на фронтенде).
        Идемпотентна: повторный вызов не меняет уже каноничный текст.
        """
        if not text:
            return text
        from src.processing.text_cleaner import (
            balance_math_delimiters,
            clean_text,
        )
        text = clean_text(text)
        for bad, good in cls._MATH_CHAR_FIXES.items():
            if bad in text:
                text = text.replace(bad, good)
        return balance_math_delimiters(text)

